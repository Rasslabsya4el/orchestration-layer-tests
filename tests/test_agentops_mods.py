def test_install_backs_up_changed_and_extra(env):
    repo, inst = env
    (inst / "DESIGN.md").write_bytes(b"changed")
    # an install-only file is an older committed version (#921: bytes in no commit would be refused)
    (repo / "mods" / "unslop" / "extra.txt").write_bytes(b"extra")
    _git(repo, "add", "-A")
    _git(repo, "commit", "-qm", "add extra")
    (repo / "mods" / "unslop" / "extra.txt").unlink()
    _git(repo, "add", "-A")
    _git(repo, "commit", "-qm", "drop extra")
    (inst / "extra.txt").write_bytes(b"extra")
    _old(inst / "DESIGN.md", inst / "extra.txt")
    assert mods.run_install("unslop") == 0
    assert mods.compare("unslop")[1] == []
    assert not (inst / "extra.txt").exists()
    backups = list((inst / ".cache").glob("backup-*"))
    assert len(backups) == 1
    assert (backups[0] / "DESIGN.md").read_bytes() == b"changed"
    assert (backups[0] / "extra.txt").read_bytes() == b"extra"


def test_install_refused_when_install_newer(env, capsys):
    _, inst = env
    (inst / "DESIGN.md").write_bytes(b"hand edit")  # mtime now, after the commit
    assert mods.run_install("unslop") == 1
    assert "refused" in capsys.readouterr().out
    assert (inst / "DESIGN.md").read_bytes() == b"hand edit"
    assert not (inst / ".cache").exists()
    assert mods.run_install("unslop", force=True) == 0
    assert mods.compare("unslop")[1] == []
    assert (next((inst / ".cache").glob("backup-*")) / "DESIGN.md").read_bytes() == b"hand edit"


@pytest.mark.parametrize("name", mods.MOD_NAMES)
def test_install_ignores_app_generated_file_but_refuses_hand_edit(env, capsys, name):
    repo, inst0 = env
    inst = inst0.parent / name
    rel = ".claude-plugin/types/claude-code-tools/index.d.ts"
    for root in (repo / "mods" / name, inst):
        (root / "hooks").mkdir(parents=True, exist_ok=True)
        (root / "hooks" / "a.ts").write_bytes(b"a")
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_bytes(b"types v1")
    _git(repo, "add", "-A")
    _git(repo, "commit", "-qm", "mod")
    (inst / rel).write_bytes(b"types v2 regenerated by the app")  # mtime now, after the commit
    assert mods.run_install(name) == 0
    assert "refused" not in capsys.readouterr().out
    assert (inst / rel).read_bytes() == b"types v2 regenerated by the app"  # #167: never copied over
    # a hand-edited source file is still refused and named
    (inst / "hooks" / "a.ts").write_bytes(b"hand edit")
    (inst / rel).write_bytes(b"types v3")
    assert mods.run_install(name) == 1
    out = capsys.readouterr().out
    assert "refused" in out and "hooks/a.ts" in out and rel not in out
    assert (inst / "hooks" / "a.ts").read_bytes() == b"hand edit"


def _commit_version(repo, rel, data):
    p = repo / "mods" / "unslop" / rel
    p.write_bytes(data)
    _git(repo, "add", "-A")
    _git(repo, "commit", "-qm", "v " + data.decode())


