def test_test_command_counts_with_fake_runner(env, capsys):
    repo, _ = env
    (repo / "mods" / "unslop" / "bin").mkdir()
    (repo / "mods" / "unslop" / "bin" / "test_a.py").write_text("")
    (repo / "mods" / "unslop" / "test").mkdir()
    (repo / "mods" / "unslop" / "test" / "a.test.tsx").write_text("")  # #833: the plugin's tests run only when a test file is on disk
    calls = []
    plugin_test = iter([(1, "18 pass\n1 fail\n  FAIL a: timed out after 5s\n"), (0, "19 pass, 0 fail\n")])

    def runner(cmd, cwd):
        calls.append((cmd[1:3], cwd.name))
        if cmd[1:3] == ["plugin", "validate"]:
            return 0, "valid\n"
        if cmd[1:3] == ["plugin", "test"]:
            return next(plugin_test)
        return 0, "49 passed in 3.2s\n"

    assert mods.run_test("unslop", runner) == 0
    out = capsys.readouterr().out
    assert "plugin test (repeated once): 19 pass, 0 fail, exit 0" in out
    assert "pytest: 49 pass, 0 fail" in out
    assert calls[0] == (["plugin", "validate"], "unslop")
    assert [c for c in calls if c[0] == ["plugin", "test"]] == [(["plugin", "test"], "unslop")] * 2
    assert mods.parse_counts("2 failed, 7 passed in 1s") == (7, 2)
    # a number at the end of a line is not the count of the word that starts the next line
    assert mods.parse_counts("done 5.14\nfailed #ff6961\n 91 pass\n 0 fail\n") == (91, 0)


def _file(root, rel, data):
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(data)


def _two_builds(repo):
    """Build A (a branch) moves draw.ts under mods/shared and adds test/new.ts; the checkout is then the older commit."""
    old = subprocess.run(["git", "rev-parse", "HEAD"], cwd=repo, capture_output=True, text=True).stdout.strip()
    _git(repo, "checkout", "-q", "-b", "build-a")
    _file(repo, "mods/shared/draw.ts", b"draw A")
    _file(repo, "mods/unslop/test/new.ts", b"new A")
    _git(repo, "add", "-A")
    _git(repo, "commit", "-qm", "build A")
    return old


def _install_build_a(repo, inst):
    _file(inst, "hooks/draw.ts", b"draw A")       # what sync_shared writes from mods/shared on build A
    _file(inst, "test/new.ts", b"new A")
    _file(inst, "hooks/x.ts", b"x")


def test_936_older_checkout_over_committed_build_a_installs(env, capsys):
    """#936 row 1+2: every file of build A is committed (on a branch) -> installing from the older commit is not refused,
    for a file moved under mods/shared in A and for a file that exists in no older commit."""
    repo, inst = env
    old = _two_builds(repo)
    _install_build_a(repo, inst)
    _git(repo, "checkout", "-q", old)
    assert mods.run_install("unslop") == 0
    out = capsys.readouterr().out
    assert "refused" not in out and "backup" in out
    assert not (inst / "hooks" / "draw.ts").exists() and not (inst / "test" / "new.ts").exists()


def test_936_hand_edit_next_to_committed_build_a_is_still_refused(env, capsys):
    repo, inst = env
    old = _two_builds(repo)
    _install_build_a(repo, inst)
    (inst / "test" / "new.ts").write_bytes(b"hand edit in no commit")
    _git(repo, "checkout", "-q", old)
    assert mods.run_install("unslop") == 1
    out = capsys.readouterr().out
    assert "refused" in out and "test/new.ts" in out and "hooks/draw.ts" not in out
